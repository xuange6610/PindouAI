  static String text(BuildContext context, String key) {
    final locale = Localizations.localeOf(context);
    final exact = locale.countryCode == null
        ? locale.languageCode
        : '${locale.languageCode}_${locale.countryCode}';
    return _values[exact]?[key] ??
        _values[locale.languageCode]?[key] ??
        _values['zh_CN']![key] ??
        key;
  }

  static String ui(BuildContext context, String chinese) {
    final locale = Localizations.localeOf(context);
    if (locale.languageCode == 'zh' && locale.countryCode != 'TW') {
      return chinese;
    }
    if (locale.languageCode == 'zh' && locale.countryCode == 'TW') {
      return _uiTraditional[chinese] ?? chinese;
    }
    return _uiEnglish[chinese] ?? chinese;
  }

